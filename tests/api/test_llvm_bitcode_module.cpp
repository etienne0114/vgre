static void test_bc_launch_noop() {
    void *mod = vgre_cuModuleLoadBitcode(kNoopBC, kNoopBCLen);
    if (!mod) {
        check("bc_launch_noop: vgre_cuModuleLoadBitcode prerequisite", false);
        return;
    }
    CUfunction fn = nullptr;
    CUresult r = cuModuleGetFunction(&fn, static_cast<CUmodule>(mod), "test_bc_noop");
    if (r != CUDA_SUCCESS || !fn) {
        check("bc_launch_noop: cuModuleGetFunction prerequisite", false);
        cuModuleUnload(static_cast<CUmodule>(mod));
        return;
    }
    // Launch 1 block × 1 thread with no arguments (no-op kernel ignores args).
    r = cuLaunchKernel(fn, 1, 1, 1, 1, 1, 1, 0, nullptr, nullptr, nullptr);
    check("bc_launch_noop: cuLaunchKernel returns CUDA_SUCCESS", r == CUDA_SUCCESS);
    cuModuleUnload(static_cast<CUmodule>(mod));
}

// Test 6: two separate BC loads produce independent handles (both JIT-compile).
static void test_bc_double_load() {
    void *mod1 = vgre_cuModuleLoadBitcode(kNoopBC, kNoopBCLen);
    void *mod2 = vgre_cuModuleLoadBitcode(kNoopBC, kNoopBCLen);
    check("bc_double_load: both handles non-null",
          mod1 != nullptr && mod2 != nullptr);
    CUfunction fn1 = nullptr, fn2 = nullptr;
    if (mod1) cuModuleGetFunction(&fn1, static_cast<CUmodule>(mod1), "test_bc_noop");
    if (mod2) cuModuleGetFunction(&fn2, static_cast<CUmodule>(mod2), "test_bc_noop");
    check("bc_double_load: both CUfunctions non-null",
          fn1 != nullptr && fn2 != nullptr);
    if (mod1) cuModuleUnload(static_cast<CUmodule>(mod1));
    if (mod2) cuModuleUnload(static_cast<CUmodule>(mod2));
}

