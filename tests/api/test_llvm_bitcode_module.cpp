// Test 1: plain PTX bytes are not misidentified as bitcode.
static void test_ptx_not_bc() {
    static const char kPTX[] =
        ".version 7.0\n.target sm_80\n.address_size 64\n"
        ".visible .entry nop_ptx() { ret; }\n";
    CUmodule mod = nullptr;
    CUresult r = cuModuleLoadData(&mod, kPTX);
    check("ptx_not_bc: cuModuleLoadData succeeds", r == CUDA_SUCCESS);
    if (mod) {
        CUfunction fn = nullptr;
        r = cuModuleGetFunction(&fn, mod, "nop_ptx");
        check("ptx_not_bc: cuModuleGetFunction succeeds (PTX still works)", r == CUDA_SUCCESS);
        cuModuleUnload(mod);
    }
}

// Test 2: vgre_cuModuleLoadBitcode registers BC and returns a valid handle.
static void test_bc_magic_detection() {
    // Verify first two bytes are 'B','C'
    check("bc_magic: blob starts with 0x42 0x43",
          kNoopBC[0] == 0x42 && kNoopBC[1] == 0x43);
    void *mod = vgre_cuModuleLoadBitcode(kNoopBC, kNoopBCLen);
    check("bc_magic: vgre_cuModuleLoadBitcode returns non-null", mod != nullptr);
    // Verify plain cuModuleLoadData correctly rejects raw BC (no size param).
    CUmodule bad_mod = nullptr;
    CUresult r = cuModuleLoadData(&bad_mod, kNoopBC);
    check("bc_magic: cuModuleLoadData correctly rejects raw BC",
          r == CUDA_ERROR_INVALID_VALUE && bad_mod == nullptr);
    if (mod) cuModuleUnload(static_cast<CUmodule>(mod));
}

// Test 3: cuModuleGetFunction JITs the bitcode and returns a valid CUfunction.
static void test_bc_get_function() {
    void *mod = vgre_cuModuleLoadBitcode(kNoopBC, kNoopBCLen);
    if (!mod) {
        check("bc_get_function: vgre_cuModuleLoadBitcode prerequisite", false);
        return;
    }
    CUfunction fn = nullptr;
    CUresult r = cuModuleGetFunction(&fn, static_cast<CUmodule>(mod), "test_bc_noop");
    check("bc_get_function: cuModuleGetFunction succeeds", r == CUDA_SUCCESS);
    check("bc_get_function: CUfunction handle non-null", fn != nullptr);
    cuModuleUnload(static_cast<CUmodule>(mod));
}

// Test 4: invalid kernel name in a BC module returns an error.
static void test_bc_missing_symbol() {
    void *mod = vgre_cuModuleLoadBitcode(kNoopBC, kNoopBCLen);
    if (!mod) {
        check("bc_missing_symbol: vgre_cuModuleLoadBitcode prerequisite", false);
        return;
    }
    CUfunction fn = nullptr;
    CUresult r = cuModuleGetFunction(&fn, static_cast<CUmodule>(mod), "does_not_exist_kernel");
    check("bc_missing_symbol: non-existent symbol returns error",
          r != CUDA_SUCCESS);
    cuModuleUnload(static_cast<CUmodule>(mod));
}

