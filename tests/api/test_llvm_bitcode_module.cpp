/**
 * Test: LLVM bitcode module direct JIT path (Track N)
 *
 * Verifies the full pipeline:
 *   BC magic detection  (cuModuleLoadData with 0x42 0x43 bytes)
 *   →  bitcode stored as __llvm_bitcode__ sentinel
 *   →  compileBitcodeKernel (parse + strip nvvm.annotations + O2 + ORC JIT)
 *   →  registerPrecompiledKernel (KernelId assigned)
 *   →  cuLaunchKernel (kernel executes without error)
 *
 * Bitcode functions use the VGRE wrapper calling convention:
 *   void fn(void** args, dim3* blockIdx, dim3* threadIdx,
 *           dim3* blockDim, dim3* gridDim, void* sharedMem, size_t sharedMemSize)
 *
 * The no-op kernel returns immediately without accessing args, so it is safe
 * to launch with zero registered argTypes (the standard case for BC kernels
 * that are registered via the direct bitcode path rather than PTX parsing).
 */

